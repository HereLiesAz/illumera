package com.hereliesaz.illumera.data.vpn

import com.wireguard.config.Config
import java.io.ByteArrayInputStream
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test

class NativeVpnConfigTest {
    @Test
    fun emptyServerAndIdentityFailBeforeProvisioning() {
        assertEquals(
            "Server and local IKE identity are required",
            validateIkev2Inputs("", "vpn.example.net", "viewer", "secret")
        )
        assertEquals(
            "Server and local IKE identity are required",
            validateIkev2Inputs("vpn.example.net", "", "viewer", "secret")
        )
    }

    @Test
    fun remoteServerMustBeHostnameNotUrlOrCredentialBearingInput() {
        assertEquals(
            "Enter a hostname or IP address, not a URL",
            validateIkev2Inputs("https://vpn.example.net", "vpn.example.net", "viewer", "secret")
        )
        assertEquals(
            "Enter a hostname or IP address, not a URL",
            validateIkev2Inputs("viewer@vpn.example.net", "vpn.example.net", "viewer", "secret")
        )
        assertEquals(
            "Enter a hostname or IP address, not a URL",
            validateIkev2Inputs("vpn.example.net/path", "vpn.example.net", "viewer", "secret")
        )
    }

    @Test
    fun ikev2RequiresActualUserCredentials() {
        assertEquals(
            "Username and password are required",
            validateIkev2Inputs("vpn.example.net", "vpn.example.net", "", "secret")
        )
        assertEquals(
            "Username and password are required",
            validateIkev2Inputs("vpn.example.net", "vpn.example.net", "viewer", "")
        )
        assertNull(validateIkev2Inputs("vpn.example.net", "vpn.example.net", "viewer", "secret"))
    }

    @Test
    fun pskAndCertificateUseTheSameValidatedLocalIkeIdentity() {
        assertEquals(
            "Server and local IKE identity are required",
            validateIkev2Server("vpn.example.net", "")
        )
        assertNull(validateIkev2Server("vpn.example.net", "client@example.net"))
        assertEquals(
            "Enter a hostname or IP address, not a URL",
            validateIkev2Server("https://vpn.example.net", "client@example.net")
        )
    }

    @Test
    fun allPlatformIkev2AuthenticationModesAreExplicit() {
        assertEquals(
            listOf(Ikev2AuthMode.EAP, Ikev2AuthMode.PSK, Ikev2AuthMode.CERTIFICATE),
            Ikev2AuthMode.entries
        )
    }

    @Test
    fun wireGuardParserRejectsMissingKeyOrMissingInterface() {
        val missingKey = "[Interface]\nAddress = 10.0.0.2/32\n"
        val missingInterface = "[Peer]\nAllowedIPs = 0.0.0.0/0\n"
        assertThrows(Exception::class.java) {
            Config.parse(ByteArrayInputStream(missingKey.toByteArray()))
        }
        assertThrows(Exception::class.java) {
            Config.parse(ByteArrayInputStream(missingInterface.toByteArray()))
        }
    }

    @Test
    fun validWireGuardClientProfileContainsOneRoutablePeer() {
        // Fixed test fixture, not generated by WireGuard's configuration serializer.
        val text = """
            [Interface]
            PrivateKey = AAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8=
            Address = 10.8.0.2/32
            DNS = 1.1.1.1
            [Peer]
            PublicKey = ICEiIyQlJicoKSorLC0uLzAxMjM0NTY3ODk6Ozw9Pj8=
            AllowedIPs = 0.0.0.0/0
            Endpoint = 198.51.100.1:51820
        """.trimIndent()

        val parsed = Config.parse(ByteArrayInputStream(text.toByteArray()))

        assertEquals(1, parsed.peers.size)
        assertTrue(parsed.peers.single().endpoint.isPresent)
    }

    @Test
    fun embeddedTunnelInitializationCannotBeHiddenByStaleDisconnectedReplay() {
        for (protocol in listOf(NativeVpnProtocol.OPENVPN, NativeVpnProtocol.SOFTETHER)) {
            val starting = NativeVpnStatus(protocol, NativeVpnPhase.CONNECTING)
            assertEquals(false, shouldAcceptEmbeddedVpnStatus(
                starting, protocol, NativeVpnPhase.DISCONNECTED))
            assertEquals(true, shouldAcceptEmbeddedVpnStatus(
                starting, protocol, NativeVpnPhase.ACTIVE))
            assertEquals(true, shouldAcceptEmbeddedVpnStatus(
                starting, protocol, NativeVpnPhase.ERROR))
            assertEquals(false, shouldAcceptEmbeddedVpnStatus(
                starting, NativeVpnProtocol.WIREGUARD, NativeVpnPhase.ACTIVE))
            assertEquals(true, shouldAcceptEmbeddedVpnStatus(
                NativeVpnStatus(protocol, NativeVpnPhase.ACTIVE),
                protocol, NativeVpnPhase.DISCONNECTED))
        }
    }

    @Test
    fun vpnAuthorizationRequiresCurrentProtocolAndAffirmativeDisclosure() {
        for (protocol in NativeVpnProtocol.entries) {
            assertEquals(false, mayRequestNativeVpnConnection(protocol, false))
            assertEquals(protocol.ready, mayRequestNativeVpnConnection(protocol, true))
        }
    }

    @Test
    fun onlyActualTunnelEnginesAreConnectable() {
        val enabled = NativeVpnProtocol.entries.filter { it.ready }.map { it.label }
        assertEquals(
            listOf("WireGuard", "IKEv2/IPsec · strongSwan / Libreswan",
                "OpenVPN", "SoftEther SSL-VPN"), enabled
        )
        assertEquals(true, NativeVpnProtocol.SOFTETHER.ready)
    }
}
